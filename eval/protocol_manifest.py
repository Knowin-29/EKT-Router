"""Reproducibility contract for paper-facing evaluation results.

The manifest deliberately separates three provenance classes:

``reproduced``
    Predictions generated from a released/local checkpoint under this protocol.
``official_api``
    Predictions generated by a versioned first-party endpoint under this protocol.
``reported``
    A value transcribed from an official paper, report, or leaderboard.

Only the first two classes can support protocol-matched cross-model aggregates.
Reported values remain useful context but must retain their source locator.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from enum import Enum
from pathlib import Path
from typing import Any, Mapping, Optional, Sequence, Tuple


SCHEMA_VERSION = "ekt-eval-manifest/1.0"


class SourceType(str, Enum):
    REPRODUCED = "reproduced"
    OFFICIAL_API = "official_api"
    REPORTED = "reported"


def canonical_json(value: Any) -> str:
    """Return a stable JSON representation used by all protocol hashes."""

    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def sha256_json(value: Any) -> str:
    return hashlib.sha256(canonical_json(value).encode("utf-8")).hexdigest()


def sha256_file(path: Path | str, chunk_size: int = 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        while chunk := stream.read(chunk_size):
            digest.update(chunk)
    return digest.hexdigest()


@dataclass(frozen=True)
class EvaluationProtocol:
    benchmark: str
    split: str
    prompt_hash: str
    decode_hash: str
    media_budget: Mapping[str, Any]
    scorer_name: str
    scorer_revision: str
    judge_name: Optional[str] = None
    judge_revision: Optional[str] = None
    tool_revision: Optional[str] = None
    knowledge_revision: Optional[str] = None

    @property
    def protocol_hash(self) -> str:
        return sha256_json(asdict(self))


@dataclass(frozen=True)
class ResultProvenance:
    model_name: str
    source_type: SourceType
    sample_count: int
    unique_sample_count: int
    model_revision: Optional[str] = None
    checkpoint_hash: Optional[str] = None
    endpoint_revision: Optional[str] = None
    source_locator: Optional[str] = None
    prediction_hash: Optional[str] = None
    notes: Tuple[str, ...] = field(default_factory=tuple)


@dataclass(frozen=True)
class EvaluationManifest:
    protocol: EvaluationProtocol
    result: ResultProvenance
    created_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(timespec="seconds")
    )
    schema_version: str = SCHEMA_VERSION

    def validation_errors(self) -> Tuple[str, ...]:
        errors = []
        if self.schema_version != SCHEMA_VERSION:
            errors.append(f"unsupported_schema:{self.schema_version}")
        if self.result.sample_count <= 0:
            errors.append("non_positive_sample_count")
        if self.result.unique_sample_count != self.result.sample_count:
            errors.append("sample_ids_not_unique_or_incomplete")
        if not self.protocol.prompt_hash:
            errors.append("missing_prompt_hash")
        if not self.protocol.decode_hash:
            errors.append("missing_decode_hash")
        if not self.protocol.scorer_name or not self.protocol.scorer_revision:
            errors.append("missing_scorer_identity")
        if self.protocol.judge_name and not self.protocol.judge_revision:
            errors.append("missing_judge_revision")

        source = self.result.source_type
        if source is SourceType.REPRODUCED:
            if not self.result.model_revision:
                errors.append("missing_model_revision")
            if not self.result.checkpoint_hash:
                errors.append("missing_checkpoint_hash")
            if not self.result.prediction_hash:
                errors.append("missing_prediction_hash")
        elif source is SourceType.OFFICIAL_API:
            if not self.result.endpoint_revision:
                errors.append("missing_endpoint_revision")
            if not self.result.prediction_hash:
                errors.append("missing_prediction_hash")
        elif source is SourceType.REPORTED:
            if not self.result.source_locator:
                errors.append("missing_reported_source_locator")
        else:  # Defensive for manifests loaded from untyped JSON.
            errors.append(f"unknown_source_type:{source}")
        return tuple(errors)

    def validate(self) -> None:
        errors = self.validation_errors()
        if errors:
            raise ValueError("invalid evaluation manifest: " + ", ".join(errors))

    def to_dict(self) -> Mapping[str, Any]:
        row = asdict(self)
        row["result"]["source_type"] = self.result.source_type.value
        row["protocol_hash"] = self.protocol.protocol_hash
        return row

    def write_json(self, path: Path | str) -> None:
        self.validate()
        target = Path(path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(
            json.dumps(self.to_dict(), ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )


def aggregate_eligible(manifests: Sequence[EvaluationManifest]) -> bool:
    """Check whether complete results share one protocol and matched source class.

    Reported rows are intentionally excluded because their media, prompting, or
    scorer contract cannot in general be proven identical from a paper value.
    """

    if not manifests:
        return False
    if any(manifest.validation_errors() for manifest in manifests):
        return False
    if any(manifest.result.source_type is SourceType.REPORTED for manifest in manifests):
        return False
    return len({manifest.protocol.protocol_hash for manifest in manifests}) == 1
